// SENSEKI FEVER 正典キャラリスト（DBの characters / character_variants から 2026-08-27 取得・sort_order順）
// 規則（CSV一括登録と同じ）: 基本色は接尾辞なしのキャラ名のみ。色違いは「名前:色」で、
// character_variants に存在する組み合わせだけが有効（例: ノコノコ:緑 は無効 → ノコノコ）
(() => {
  const BASE = ['マリオ', 'ルイージ', 'ピーチ', 'デイジー', 'ロゼッタ', 'ポリーン', 'ワリオ', 'ワルイージ',
    'キノピオ', 'キノピコ', 'チコ', 'ヨッシー', 'クッパ', 'クッパJr.', 'ドンキーコング', 'テレサ',
    'ヘイホー', 'ノコノコ', 'カメック', 'ガボン', 'ディディーコング', 'ワンワン', 'キャサリン', 'パタパタ',
    'ボスパックン', 'パックンフラワー', 'ブンブン', 'ゲッソー', 'ほねクッパ', 'カロン', 'ベビィマリオ',
    'ベビィルイージ', 'ベビィピーチ', 'ベビィワリオ', 'ベビィワルイージ', 'ハナチャン', 'トッテン', 'クリボー'];
  const VARIANTS = ['ヘイホー:青', 'パタパタ:青', 'ノコノコ:青', 'ヨッシー:青', 'チコ:緑', 'マリオ:オーバーオール',
    'ヨッシー:水色', 'ノコノコ:赤', 'パタパタ:緑', 'ヘイホー:緑', 'チコ:赤', 'チコ:青', 'ヨッシー:オレンジ',
    'パタパタ:黄', 'ノコノコ:黄', 'ヘイホー:水色', 'ヘイホー:オレンジ', 'チコ:オレンジ', 'ヨッシー:ピンク',
    'ヨッシー:紫', 'チコ:黒', 'ヘイホー:ピンク', 'ヘイホー:黄', 'ヨッシー:赤', 'チコ:水色', 'ヨッシー:黄'];
  // 候補リスト: 基本名の直後にその色違いを続ける（sort_order順のまま）
  const ALL = [];
  for (const b of BASE) { ALL.push(b); for (const v of VARIANTS) if (v.startsWith(b + ':')) ALL.push(v); }
  const SET = new Set(ALL);
  // ラベル正規化: 正典にない「名前:色」（デフォルト色の冗長表記・誤ラベル）は基本名へ落とす
  const canon = label => {
    const s = String(label ?? '').trim();
    if (!s.includes(':')) return s;
    return SET.has(s) ? s : s.split(':')[0];
  };
  window.Characters = { BASE, VARIANTS, ALL, SET, canon };
})();
